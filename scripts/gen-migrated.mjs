// Generates i18n/migrated.json — the paths that have already moved to app/.
//
// ponytail: migration scaffolding with a defined end. Delete this script,
// i18n/migrated.json, and the skip branch in middleware.ts at the switch
// (#120), when nothing is left under pages/.
//
// Why it exists: next-intl's middleware rewrites every path to carry a locale
// segment, which pages/ routes do not have — so with the middleware live, every
// unmigrated route 404s. That would leave the branch unpreviewable for the
// whole migration. Skipping the middleware for unmigrated paths gives back the
// English site as a working preview throughout; Italian arrives per route as it
// migrates.
//
// It is generated rather than hand-kept for the obvious reason: a hand-kept
// list of which routes moved would be the sixth hand-kept routing list in this
// repo, and removing those is the entire point of the project.
//
// Run: npm run gen:migrated   (check:routes fails if the file is stale)

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { appRoutePaths, routeAtPath } from './lib/app-routes.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'i18n/migrated.json';

const internal = appRoutePaths(ROOT);

// A migrated route has to be matched by whichever external path the visitor
// typed, not by its internal one: /clienti and /customers are the same route,
// and only one of them is what the middleware sees.
const routes = JSON.parse(readFileSync(join(ROOT, 'i18n/routes.json'), 'utf8'));
const external = new Set();

for (const path of internal) {
  const route = routeAtPath(routes, path);
  if (route) {
    for (const p of Object.values(route.paths)) external.add(p);
  } else {
    // A route with no registry entry — the harness-check probe is the only one,
    // and it is deliberate. check:routes is what stops a real page hiding here.
    external.add(path);
  }
}

const payload = {
  _comment:
    'GENERATED by scripts/gen-migrated.mjs — do not edit. Paths already served by app/. ' +
    'Temporary migration scaffolding, deleted at the switch (#120).',
  paths: [...external].sort(),
};

const serialized = JSON.stringify(payload, null, 2) + '\n';
const previous = existsSync(join(ROOT, OUT)) ? readFileSync(join(ROOT, OUT), 'utf8') : '';

if (process.argv.includes('--check')) {
  if (serialized !== previous) {
    console.error(
      `[FAIL] ${OUT} is stale — a route moved to app/ without it being regenerated.\n` +
        '       Unmigrated paths would keep bypassing the middleware, so the moved page\n' +
        '       would render without its locale. Run: npm run gen:migrated',
    );
    process.exit(1);
  }
  console.log(`[OK] ${OUT}: ${payload.paths.length} migrated path(s), in sync`);
} else {
  writeFileSync(join(ROOT, OUT), serialized);
  console.log(`[OK] wrote ${OUT}: ${payload.paths.length} migrated path(s)`);
}
